# ---- widgets baked from the GFX ports ----
def ring(w, h, r, t=2):
    """Rounded-rect outline t px thick (filled rect minus the inset filled rect: no corner gaps)."""
    o, i = G(w, h), G(w, h)
    o.fill_round_rect(0, 0, w, h, r)
    i.fill_round_rect(t, t, w - 2 * t, h - 2 * t, r - t)
    return o.a & (1 - i.a)


