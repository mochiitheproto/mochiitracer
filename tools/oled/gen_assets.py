total += len(cbits) + len(cg) * 8


def cstr(s):
    """C string literal of the UTF-8 bytes (a hex escape never swallows the next character)."""
    out, after_hex = [], False
    for b in s.encode('utf-8'):
        c = chr(b)
        if 0x20 <= b < 0x7F and c not in '"\\':
            if after_hex and c in '0123456789abcdefABCDEF':
                out.append('" "')
            out.append(c)
            after_hex = False
        else:
            out.append(f'\\x{b:02X}')
            after_hex = True
    return '"' + ''.join(out) + '"'


def readable(s):
    return ''.join(ch if ch.isprintable() else f'\\x{ord(ch):02x}' for ch in s)


pool = {}


def ref(s):
    if s is None:
        return 'nullptr'
    if s not in pool:
        pool[s] = f'softTxt{len(pool)}'
    return pool[s]


