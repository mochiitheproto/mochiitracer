def emit(cname, a, note=''):
    global total
    a = np.asarray(a, np.uint8)
    h, w = a.shape
    data = pack(a)
    total += len(data)
    cpp.append(f'static const uint8_t {cname}Bits[] PROGMEM = {{ ' + ', '.join(f'0x{b:02X}' for b in data) + ' };')
    cpp.append(f'PROGMEM const SoftIcon {cname} = {{{w}, {h}, {cname}Bits}};')
    hdr.append(f'extern const SoftIcon {cname};' + (f'  // {w}x{h} {note}' if note else f'  // {w}x{h}'))


def interior(a):
    """Pixels enclosed by the outline of a (flood fill from the border)."""
    h, w = a.shape
    outside = np.zeros_like(a)
    stack = [(y, x) for y in range(h) for x in (0, w - 1)] + [(y, x) for x in range(w) for y in (0, h - 1)]
    while stack:
        y, x = stack.pop()
        if 0 <= y < h and 0 <= x < w and not outside[y, x] and not a[y, x]:
            outside[y, x] = 1
            stack += [(y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)]
    return (1 - outside) & (1 - a)


