#!/usr/bin/env python3
"""Generates SoftAssets.h + SoftAssets.cpp (fonts, icons, baked widgets) for the OLED HUD.

    python3 tools/oled/gen_assets.py lib/ProtoTracer/ExternalDevices/Displays

Sources (edit these, not the generated files):
  textos.py   every word on the screen, in each language (es, en, zh)
  font5x7.py  hand-drawn 5x7 caps (+ accents, the private glyphs \\x01-\\x05)
  fonts/      the Chinese characters textos.py uses (Fusion Pixel 12px subset, OFL-1.1; how to
              add more: fonts/README.md)
  icons.py    16x16 setting icons, 12x12 pictograms (+ native 2 px ones), sparkles, the
              coolant warning light, the boop status line (hand + check)
  fan.py      the fan icon (procedural, 3 rotation frames)
  softpix.py  EPX 2x smoother + exact ports of the Adafruit_GFX primitives
Big font, setting icons and pictograms are the EPX 2x of the 1 px art, so they share one
soft 2 px stroke. Widgets are drawn with the GFX ports and stored as bitmaps, so the GFX
circle/round-rect code is never linked. Needs numpy. Output is deterministic.

Stops with an error (and writes nothing) if a string of textos.py uses a character without a
glyph or does not fit the screen: that shows up here, never on the head.
"""
